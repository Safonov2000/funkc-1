

#include<iostream>
#include<cmath>

using namespace std;

int kvadraturavnen(double a, double b, double c, double& x1, double& x2) { // Функция решения квадратного уравнения

	if (a == 0) { // Проверям, если а равно нулю

		return -1; // Ошибка
	}


	double Discriminant = b * b - 4 * a * c; // Формула дискриминанта

	if (Discriminant > 0) { // Проверяем, если дискриминант больше нуля

		x1 = (-b + sqrt(Discriminant) / (2 * a)); // Тогда делаем формулу х1

		x2 = (-b + sqrt(Discriminant) / (2 * a)); // Делаем формулу х2

		return 2; // Возвращаем 2 корня
	}

	else if (Discriminant == 0) { // Если дискриминант равен нулю

		x1 = -b / (2 * a); // Вычисляем 1 корень

		x2 = x1; // Записываем корень в 2

		return 1; // Возвращаем 1
	}
	else { // Иначе

		return 0; // Нет корней
	}

}

