	double x1, x2; // Переменные корни

	cout << "Введите коэффициент а: "; // Просим пользователя ввести коэффициент а

	cin >> a; // Сохраняем в переменную а

	cout << "Введите коэффициент b: "; // Просим пользователя ввести коэффициент b

	cin >> b; // Сохраняем переменную b

	cout << "Введите коэффициент c: "; // Просим пользователя ввести коэффициент c

	cin >> c; // Сохраняем переменную с

	int result = kvadraturavnen(a, b, c, x1, x2); // Делаем вызов функции решения

	if (result == 2) { // если result имеет 2 корня

		cout << "x1" << x1 << "\n"; // Выводим первый корень

		cout << "x2" << x2 << "\n"; // Выводим второй корень

	}

	else if (result == 1) { // Если result имеет 1 корень

		cout << "x" << x1 << "\n"; // Выводим один корень
	}

